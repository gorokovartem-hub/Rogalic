"""
=== РЕДКОСТИ (RARITIES) ===
RARITIES: id -> (название, цвет, вес, рост веса за вагон)
  вес      шанс выпадения редкости при открытии сундука (относительный)
  рост     на сколько растёт вес за каждый пройденный вагон (глубже — чаще редкие)
Сундук с босса даёт множитель к шансам редких (bonus).
PERK_RARITY: id перка -> id редкости. Перк без записи считается обычным.
"""

RARITIES = {
    "common": ("Обычный", (190, 195, 205), 60, 0.0),
    "rare": ("Редкий", (90, 170, 255), 28, 0.03),
    "epic": ("Эпический", (190, 100, 255), 9, 0.06),
    "legendary": ("Легендарный", (255, 190, 60), 2, 0.05),
}

PERK_RARITY = {
    "rapid": "common", "speed": "common", "hp": "common", "dash": "common", "cold": "common",
    "heavy": "rare", "multi": "rare", "bounce": "rare", "pierce": "rare", "shield": "rare", "vamp": "rare",
    "arc": "rare",
    "overdrive": "epic", "titan": "epic", "ghostshot": "epic", "blast": "epic", "ram": "epic",
    "goldbullet": "legendary", "conductor": "legendary", "engine": "legendary", "nova": "legendary",
}


def rarity_of(key):
    return PERK_RARITY.get(key, "common")


def roll_perks(n, depth, bonus=1.0, rng=None):
    """Выбрать n РАЗНЫХ перков: сначала редкость по весам, потом случайный перк этой редкости."""
    import random as _random
    rng = rng or _random
    pools = {}
    for p in PERKS:
        pools.setdefault(rarity_of(p[0]), []).append(p)
    out = []
    for _ in range(n):
        ids = [r for r in RARITIES if pools.get(r)]
        if not ids:
            break
        w = []
        for r in ids:
            _, _, base, grow = RARITIES[r]
            val = base * (1 + grow * depth)
            if r != "common":
                val *= bonus
            w.append(val)
        r = rng.choices(ids, w)[0]
        perk = rng.choice(pools[r])
        pools[r].remove(perk)
        out.append(perk)
    return out